import Foundation

//--------------------------------------------------------------------------------------------------

public extension UInt64 {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var binarySerialData : Data {
    var data = Data ()
    data.append (UInt8 ((self & 0x0F) | 0x80))
    var v = self >> 4
    while v > 0 {
      data.append (UInt8 (v & 0x7F))
      v >>= 7
    }
    return data
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

