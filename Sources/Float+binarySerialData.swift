import Foundation

//--------------------------------------------------------------------------------------------------

public extension Float {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var binarySerialData : Data {
    var u32 = self.bitPattern
    var data = Data ()
    data.append (UInt8 ((u32 >> 28) | 0xB0))
    u32 <<= 4
    while u32 > 0 {
      data.append (UInt8 (u32 >> 25))
      u32 <<= 7
    }
    return data
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

