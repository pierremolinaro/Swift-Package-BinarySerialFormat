import Foundation

//--------------------------------------------------------------------------------------------------

public extension BinarySendCodeProtocol {

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

  var binarySerialData : Data {
    var byte = self.rawValue | 0xC0
    let data = unsafe Data (bytes: &byte, count: 1)
    return data
  }

  // - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

}

